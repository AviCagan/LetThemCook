// Beaker Buddies: all pixel art, code-defined, Game Boy Color flavour.
// Every sprite is a palette (single char -> "#rrggbb") plus a list of frames;
// each frame is h strings of w chars and "." is always transparent.
//
// Characters are 16x20, anchored bottom-centre, 12 frames in the order
//   [down0, down1, down2, up0, up1, up2, left0, left1, left2, right0, right1, right2]
// where *0 is standing and *1/*2 are the two walk poses (left foot / right foot).
// Lab pets are 16x16, anchored bottom-centre (feet on the anchor), 6 frames
//   [idle0, idle1, walkLeft0, walkLeft1, walkRight0, walkRight1]
// idle frames face the camera, walk frames are side views (right = mirrored left).
// Tiles are 16x16 anchored top-left; icons 16x16 anchored centre; emotes 16x16
// anchored bottom-centre (sit the anchor on top of a head). ui_frame is a 9-slice
// on an 8px grid. Edit the rows directly; tests/sprites.test.ts checks every row.
//
// Common character chars: o outline, k eyes, w coat (white), c coat shade,
// s skin/fur, d fur shade, a accent (shirt / accessory), p pink, h extra.

export interface SpriteDef {
  w: number;
  h: number;
  palette: Record<string, string>; // single char -> '#rrggbb'; '.' is always transparent
  frames: string[][]; // frames[i] = exactly h strings of exactly w chars
  anchor?: [number, number]; // default [0.5, 1]
}

